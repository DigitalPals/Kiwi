"""Writes Kiwi's launcher, notification and in-app logo icons as vector drawables.

Usage: python3 android/scripts/make-icons.py web/public/icons/icon.svg android/app/src/main/res

The kiwi slice comes from the web app's icon (web/public/icons/icon.svg): its rind, flesh and
core gradients, the rays, the seeds and the highlight. The SVG's blurred drop shadow is left
out (launchers draw their own). Outputs:

- mipmap-anydpi/ic_launcher.xml: the adaptive icon (background, foreground, monochrome)
- drawable/ic_launcher_background.xml: the icon's pale green gradient, full bleed
- drawable/ic_launcher_foreground.xml: the slice inside the 66 dp safe zone
- drawable/ic_launcher_monochrome.xml: the slice's outline and seeds for themed icons
- drawable/ic_stat_kiwi.xml: the monochrome slice in white for notifications
- drawable/kiwi_slice.xml: the slice alone, for the app's screens
- drawable/kiwi_tile.xml: the whole icon (tile and slice), for the app's screens
"""
import math
import os
import re
import sys
import xml.etree.ElementTree as ET

SVG = "{http://www.w3.org/2000/svg}"
ANDROID = 'xmlns:android="http://schemas.android.com/apk/res/android"'
AAPT = 'xmlns:aapt="http://schemas.android.com/aapt"'
HEADER = "<!-- Generated by android/scripts/make-icons.py from web/public/icons/icon.svg. -->"


def argb(color, opacity=1.0):
    color = color.lstrip("#")
    if len(color) == 3:
        color = "".join(c * 2 for c in color)
    alpha = round(max(0.0, min(1.0, opacity)) * 255)
    return f"#{alpha:02X}{color.upper()}"


def num(value):
    return f"{value:.2f}".rstrip("0").rstrip(".")


def ellipse_path(cx, cy, rx, ry):
    return (f"M{num(cx - rx)},{num(cy)}a{num(rx)},{num(ry)} 0 1,0 {num(2 * rx)},0"
            f"a{num(rx)},{num(ry)} 0 1,0 {num(-2 * rx)},0Z")


class Icon:
    """The parts of icon.svg, in its 512 × 512 coordinates."""

    def __init__(self, path):
        root = ET.parse(path).getroot()
        self.gradients = {}
        for grad in root.iter():
            tag = grad.tag.replace(SVG, "")
            if tag in ("linearGradient", "radialGradient"):
                stops = [(float(s.get("offset")), s.get("stop-color")) for s in grad if s.tag == f"{SVG}stop"]
                self.gradients[grad.get("id")] = (tag, {k: float(v) for k, v in grad.attrib.items() if k not in ("id",)}, stops)
        body = [el for el in root if el.tag != f"{SVG}defs"]
        self.background = body[0]
        # body[1] is the blurred shadow.
        circles = [el for el in body if el.tag == f"{SVG}circle"]
        self.skin, self.rim, self.flesh = circles
        self.rays = next(el for el in body if el.tag == f"{SVG}path" and el.get("stroke") == "#f4fbd8")
        self.core = [el for el in body if el.tag == f"{SVG}ellipse"][-1]
        seeds = next(el for el in body if el.tag == f"{SVG}g")
        self.seed_color = seeds.get("fill")
        self.seeds = []
        for seed in seeds:
            angle, px, py = map(float, re.match(r"rotate\(([-\d.]+) ([-\d.]+) ([-\d.]+)\)", seed.get("transform")).groups())
            self.seeds.append((float(seed.get("cx")), float(seed.get("cy")), float(seed.get("rx")), float(seed.get("ry")), angle, px, py))
        self.highlight = [el for el in body if el.tag == f"{SVG}path"][-1]

    def fill(self, ref, box):
        """A gradient as an aapt:attr fill, mapped from objectBoundingBox units into [box]."""
        kind, attrs, stops = self.gradients[re.match(r"url\(#(\w+)\)", ref).group(1)]
        x, y, w, h = box
        items = "".join(f'<item android:offset="{num(o)}" android:color="{argb(c)}" />' for o, c in stops)
        if kind == "linearGradient":
            head = (f'<gradient android:type="linear" android:startX="{num(x + attrs.get("x1", 0) * w)}" '
                    f'android:startY="{num(y + attrs.get("y1", 0) * h)}" android:endX="{num(x + attrs.get("x2", 1) * w)}" '
                    f'android:endY="{num(y + attrs.get("y2", 0) * h)}">')
        else:
            head = (f'<gradient android:type="radial" android:centerX="{num(x + attrs.get("cx", .5) * w)}" '
                    f'android:centerY="{num(y + attrs.get("cy", .5) * h)}" '
                    f'android:gradientRadius="{num(attrs.get("r", .5) * (w + h) / 2)}">')
        return f'<aapt:attr name="android:fillColor">{head}{items}</gradient></aapt:attr>'

    def slice(self, mono=None):
        """The slice's paths; [mono] draws the outline and seeds in one colour instead."""
        def circle(el, scale=1.0):
            cx, cy, r = (float(el.get(k)) for k in ("cx", "cy", "r"))
            return cx, cy, r * scale

        out = []
        if mono:
            cx, cy, r = circle(self.skin)
            out.append(f'<path android:fillColor="{mono}" android:fillType="evenOdd" '
                       f'android:pathData="{ellipse_path(cx, cy, r, r)}{ellipse_path(cx, cy, r * 0.86, r * 0.86)}" />')
        else:
            for el in (self.skin, self.rim, self.flesh):
                cx, cy, r = circle(el)
                fill = el.get("fill")
                path = ellipse_path(cx, cy, r, r)
                if fill.startswith("url("):
                    out.append(f'<path android:pathData="{path}">{self.fill(fill, (cx - r, cy - r, 2 * r, 2 * r))}</path>')
                else:
                    out.append(f'<path android:fillColor="{argb(fill)}" android:pathData="{path}" />')
            out.append(f'<path android:strokeColor="{argb(self.rays.get("stroke"), float(self.rays.get("stroke-opacity")))}" '
                       f'android:strokeWidth="{self.rays.get("stroke-width")}" android:strokeLineCap="round" '
                       f'android:pathData="{self.rays.get("d")}" />')
        cx, cy, rx, ry = (float(self.core.get(k)) for k in ("cx", "cy", "rx", "ry"))
        if mono:
            out.append(f'<path android:fillColor="{mono}" android:pathData="{ellipse_path(cx, cy, rx, ry)}" />')
        else:
            out.append(f'<path android:pathData="{ellipse_path(cx, cy, rx, ry)}">'
                       f'{self.fill(self.core.get("fill"), (cx - rx, cy - ry, 2 * rx, 2 * ry))}</path>')
        seed = mono or argb(self.seed_color)
        for sx, sy, rx, ry, angle, px, py in self.seeds:
            out.append(f'<group android:rotation="{num(angle)}" android:pivotX="{num(px)}" android:pivotY="{num(py)}">'
                       f'<path android:fillColor="{seed}" android:pathData="{ellipse_path(sx, sy, rx, ry)}" /></group>')
        if not mono:
            h = self.highlight
            out.append(f'<path android:strokeColor="{argb(h.get("stroke"), float(h.get("stroke-opacity")))}" '
                       f'android:strokeWidth="{h.get("stroke-width")}" android:strokeLineCap="round" '
                       f'android:pathData="{h.get("d")}" />')
        return out

    def center(self):
        return float(self.skin.get("cx")), float(self.skin.get("cy")), float(self.skin.get("r"))

    def tile(self):
        w = float(self.background.get("width"))
        h = float(self.background.get("height"))
        return f'<path android:pathData="M0,0h{num(w)}v{num(h)}h{num(-w)}Z">{self.fill(self.background.get("fill"), (0, 0, w, h))}</path>'


def vector(size, viewport, parts, group=None):
    body = "\n    ".join(parts)
    if group:
        body = f"<group {group}>\n    {body}\n    </group>"
    return f'''<?xml version="1.0" encoding="utf-8"?>
{HEADER}
<vector {ANDROID}
    {AAPT}
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{num(viewport)}"
    android:viewportHeight="{num(viewport)}">
    {body}
</vector>
'''


def fitted(icon, canvas, radius):
    """A group that puts the slice's centre in the middle of [canvas] with the given radius."""
    cx, cy, r = icon.center()
    scale = radius / r
    return (f'android:scaleX="{scale:.5f}" android:scaleY="{scale:.5f}" '
            f'android:translateX="{num(canvas / 2 - cx * scale)}" android:translateY="{num(canvas / 2 - cy * scale)}"')


def main():
    icon = Icon(sys.argv[1])
    res = sys.argv[2]
    os.makedirs(f"{res}/drawable", exist_ok=True)
    os.makedirs(f"{res}/mipmap-anydpi", exist_ok=True)
    files = {
        # Adaptive icons are 108 dp; launchers show at least the middle 72 dp and keep the 66 dp
        # circle. A 30 dp radius keeps the web icon's proportions inside that circle.
        "drawable/ic_launcher_background.xml": vector(108, 108, [icon.tile()], 'android:scaleX="0.2109375" android:scaleY="0.2109375"'),
        "drawable/ic_launcher_foreground.xml": vector(108, 108, icon.slice(), fitted(icon, 108, 30)),
        "drawable/ic_launcher_monochrome.xml": vector(108, 108, icon.slice(mono="#FF000000"), fitted(icon, 108, 30)),
        "drawable/ic_stat_kiwi.xml": vector(24, 24, icon.slice(mono="#FFFFFFFF"), fitted(icon, 24, 10.5)),
        "drawable/kiwi_slice.xml": vector(48, 512, icon.slice(), fitted(icon, 512, 254)),
        "drawable/kiwi_tile.xml": vector(48, 512, [icon.tile()] + icon.slice()),
    }
    for name, text in files.items():
        with open(f"{res}/{name}", "w") as out:
            out.write(text.replace(f"{AAPT}\n    ", "") if "aapt:attr" not in text else text)
    with open(f"{res}/mipmap-anydpi/ic_launcher.xml", "w") as out:
        out.write(f'''<?xml version="1.0" encoding="utf-8"?>
{HEADER}
<adaptive-icon {ANDROID}>
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''')


if __name__ == "__main__":
    main()
