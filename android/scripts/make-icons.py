"""Writes Kiwi's launcher and notification icons as vector drawables (the web app's kiwi slice)."""
# Usage: python3 android/scripts/make-icons.py android/app/src/main/res
import math, sys, os
res = sys.argv[1]
os.makedirs(f"{res}/drawable", exist_ok=True)
os.makedirs(f"{res}/mipmap-anydpi", exist_ok=True)
NS = 'xmlns:android="http://schemas.android.com/apk/res/android"'

def ellipse(cx, cy, rx, ry):
    return f"M{cx-rx:.2f},{cy:.2f}a{rx:.2f},{ry:.2f} 0 1,0 {2*rx:.2f},0a{rx:.2f},{ry:.2f} 0 1,0 {-2*rx:.2f},0Z"

def circle(cx, cy, r):
    return ellipse(cx, cy, r, r)

def slice_paths(c, scale, mono=False):
    out = []
    s = scale  # radius of the slice
    if not mono:
        out.append(f'<path android:fillColor="#FF6A4524" android:pathData="{circle(c, c, s)}" />')
        out.append(f'<path android:fillColor="#FFDCEF9E" android:pathData="{circle(c, c, s*0.93)}" />')
        out.append(f'<path android:fillColor="#FF86BF38" android:pathData="{circle(c, c, s*0.908)}" />')
        rays = []
        for i in range(28):
            a = i / 28 * math.pi * 2
            outer = s * (0.73 + (i % 3) * 0.05)
            inner = s * 0.31
            rays.append(f"M{c+math.cos(a)*inner:.2f},{c+math.sin(a)*inner:.2f}L{c+math.cos(a)*outer:.2f},{c+math.sin(a)*outer:.2f}")
        out.append(f'<path android:strokeColor="#66F4FBD8" android:strokeWidth="{s*0.017:.2f}" android:strokeLineCap="round" android:pathData="{"".join(rays)}" />')
        out.append(f'<path android:fillColor="#FFF7F8DE" android:pathData="{ellipse(c, c, s*0.23, s*0.204)}" />')
        seed = "#FF2A1D10"
    else:
        # Monochrome (themed icon): the rind and the seeds.
        out.append(f'<path android:fillColor="#FF000000" android:fillType="evenOdd" android:pathData="{circle(c, c, s)}{circle(c, c, s*0.86)}" />')
        out.append(f'<path android:fillColor="#FF000000" android:pathData="{ellipse(c, c, s*0.23, s*0.204)}" />')
        seed = "#FF000000"
    for i in range(18):
        a = i / 18 * math.pi * 2
        r = s * (0.375 + (i % 2) * 0.054)
        x, y = c + math.cos(a) * r, c + math.sin(a) * r
        deg = a * 180 / math.pi + 90
        out.append(f'<group android:rotation="{deg:.1f}" android:pivotX="{x:.2f}" android:pivotY="{y:.2f}"><path android:fillColor="{seed}" android:pathData="{ellipse(x, y, s*0.027, s*0.06)}" /></group>')
    return "\n    ".join(out)

def vector(size, viewport, body):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/scripts/make-icons.py from the web app's kiwi slice. -->
<vector {NS}
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
    {body}
</vector>
'''

open(f"{res}/drawable/ic_launcher_foreground.xml", "w").write(vector(108, 108, slice_paths(54, 31)))
open(f"{res}/drawable/ic_launcher_monochrome.xml", "w").write(vector(108, 108, slice_paths(54, 31, mono=True)))
# Notification icon: white on transparent, 24dp.
open(f"{res}/drawable/ic_stat_kiwi.xml", "w").write(vector(24, 24, slice_paths(12, 10, mono=True).replace("#FF000000", "#FFFFFFFF")))
open(f"{res}/mipmap-anydpi/ic_launcher.xml", "w").write(f'''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon {NS}>
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''')
